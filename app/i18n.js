// Phrases the Claude app uses as generic "done" bodies, in any language we know.
const GENERIC_WAITING = [STRINGS.en.waitingPhrases, STRINGS.tr.waitingPhrases];

function pick(language, locale) {
  let lang = language && language !== 'auto' ? language : String(locale || 'en').slice(0, 2).toLowerCase();
  if (!STRINGS[lang]) lang = 'en';
  return { lang, t: STRINGS[lang] };
}

